export function localizeLabel(text, lang) {
  if (lang !== 'en') return text;
  const s = String(text ?? '');
  const exact = {
    '无工作区（临时对话）': 'No Workspace (Ad-hoc)',
    'Thinking（深度推理）': 'Thinking (Reasoning)',
    'Gemini 共享配额池': 'Gemini Shared Pool',
    'Gemini Flash 配额池': 'Gemini Flash Pool',
    'Claude & GPT 共享配额池': 'Claude & GPT Shared Pool',
    'Claude 系列配额池': 'Claude Quota Pool',
    'GPT 系列配额池': 'GPT Quota Pool',
    '模型配额池': 'Model Quota Pool',
    '内置默认参考表': 'Built-in reference rates',
    '已重置为内置默认参考表': 'Reset to built-in defaults',
    'AI 联网核实更新': 'AI web-verified update',
    '手动编辑保存': 'Manually edited',
  };
  if (exact[s]) return exact[s];
  if (s.startsWith('会话 ')) return `Session ${s.slice(3)}`;
  if (s.includes('官方 API 定价页')) return s.replace('官方 API 定价页 + 实时汇率', 'Official API Pricing + Live FX');
  return s;
}
